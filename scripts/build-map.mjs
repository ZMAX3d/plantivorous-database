#!/usr/bin/env node
/**
 * Build a dependency-free world map for the Plantivorous static app.
 *
 * Source: Natural Earth 110m Admin 0 Countries (public domain), fetched from
 * the natural-earth-vector GeoJSON mirror. The output is a plain JS global so
 * the map works from file:// as well as a web server.
 *
 * Output: assets/js/world-map.js
 *
 * Usage: node scripts/build-map.mjs
 */

import { readFile, writeFile } from "node:fs/promises";
import { existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { tmpdir } from "node:os";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const WIDTH = 1000;
const HEIGHT = 400;
const LAT_TOP = 84;
const LAT_BOTTOM = -60;
const LON_LEFT = -180;
const LON_RIGHT = 180;

const candidatePaths = [
  join(ROOT, "data", "ne_110m_admin_0_countries.geojson"),
  join(tmpdir(), "ne_110m_countries.geojson"),
];

const sourcePath = candidatePaths.find((path) => existsSync(path));
if (!sourcePath) {
  console.error(
    "Natural Earth GeoJSON not found. Download ne_110m_admin_0_countries.geojson into data/ first."
  );
  process.exit(1);
}

const geo = JSON.parse(await readFile(sourcePath, "utf8"));

const project = ([lon, lat]) => {
  const x = ((lon - LON_LEFT) / (LON_RIGHT - LON_LEFT)) * WIDTH;
  const y = ((LAT_TOP - lat) / (LAT_TOP - LAT_BOTTOM)) * HEIGHT;
  return [Math.round(x * 10) / 10, Math.round(y * 10) / 10];
};

function ringToPath(ring) {
  if (!ring.length) return "";
  const segments = [];
  let current = [];
  let previousLon = null;

  for (const coordinate of ring) {
    const [lon, lat] = coordinate;
    if (previousLon !== null && Math.abs(lon - previousLon) > 180) {
      if (current.length > 1) segments.push(current);
      current = [];
    }
    current.push(project([lon, lat]));
    previousLon = lon;
  }
  if (current.length > 1) segments.push(current);

  return segments
    .map((segment) => {
      const [first, ...rest] = segment;
      return `M${first[0]} ${first[1]}${rest
        .map(([x, y]) => `L${x} ${y}`)
        .join("")}Z`;
    })
    .join("");
}

function geometryToPath(geometry) {
  if (!geometry) return "";
  if (geometry.type === "Polygon") {
    return geometry.coordinates.map(ringToPath).join("");
  }
  if (geometry.type === "MultiPolygon") {
    return geometry.coordinates
      .flatMap((polygon) => polygon.map(ringToPath))
      .join("");
  }
  return "";
}

const countries = [];
for (const feature of geo.features) {
  const name =
    feature.properties?.ADMIN ||
    feature.properties?.NAME ||
    feature.properties?.name ||
    "Unknown";
  const d = geometryToPath(feature.geometry);
  if (!d) continue;
  countries.push({
    name,
    continent: feature.properties?.CONTINENT || "",
    d,
  });
}
countries.sort((a, b) => a.name.localeCompare(b.name));

const graticule = [];
for (let lon = -180; lon <= 180; lon += 30) {
  const points = [];
  for (let lat = LAT_BOTTOM; lat <= LAT_TOP; lat += 2) {
    points.push(project([lon, lat]));
  }
  graticule.push({
    type: "meridian",
    d: `M${points.map(([x, y]) => `${x} ${y}`).join("L")}`,
  });
}
for (let lat = -60; lat <= 80; lat += 20) {
  const points = [];
  for (let lon = -180; lon <= 180; lon += 2) {
    points.push(project([lon, lat]));
  }
  graticule.push({
    type: "parallel",
    d: `M${points.map(([x, y]) => `${x} ${y}`).join("L")}`,
  });
}

const payload = {
  width: WIDTH,
  height: HEIGHT,
  latTop: LAT_TOP,
  latBottom: LAT_BOTTOM,
  lonLeft: LON_LEFT,
  lonRight: LON_RIGHT,
  projection: "equirectangular",
  source: "Natural Earth 110m Admin 0 Countries (public domain)",
  countries,
  graticule,
};

const js = `/* Generated by scripts/build-map.mjs — Natural Earth public-domain geometry. */\nwindow.PLANTIVOROUS_WORLD = ${JSON.stringify(payload)};\n`;
await writeFile(join(ROOT, "assets", "js", "world-map.js"), js, "utf8");

console.log(
  `Wrote assets/js/world-map.js: ${countries.length} countries, ${(
    Buffer.byteLength(js) / 1024
  ).toFixed(0)} KB`
);
